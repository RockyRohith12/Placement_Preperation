package Java.datatypes;

public class loops {
    public static void main(String[] args){


        //for loop

        for(int i = 0; i<=10; i++){
            System.out.println("Hello");
        }

        // while loop

        int j = 1;   // fist variable is declared and then the condition is checked
        
        while(j <=5){
            System.out.println("Hi");
            j++;
        }


        //do - while loop = first prints statement and then checks the condition

        int k = 1;

        do{
            System.out.println(k);
            k++;
        } while(k==20);

        

    }
}
